describe('flip honesty regexes', () => {
  const HONEST =
    'Within the tested range, no single factor on its own reached a tipping point that would change which option leads.';
  const DISHONEST =
    'The picture appears fragile, so even small adjustments to the strongest drivers could shift which option leads.';

  it('honest marker matches the no-tipping-point copy, not the dishonest one', () => {
    expect(FLIP_NO_TIPPING_POINT_RE.test(HONEST)).toBe(true);
  });

  it('could-flip claim matches the dishonest copy, not the honest one', () => {
    expect(FLIP_COULD_FLIP_CLAIM_RE.test(DISHONEST)).toBe(true);
    expect(FLIP_COULD_FLIP_CLAIM_RE.test(HONEST)).toBe(false);
  });
});

