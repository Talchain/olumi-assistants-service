/**
 * orchestrator-eval — decision_review fixture loading, extraction and the
 * fixture-regression loop.
 *
 * Mirrors `src/run.ts` (the routing chassis) so both tasks share one shape:
 * load the checked-in pack, score every recorded candidate, and compare each
 * verdict against the fixture's `expected` map. A disagreement exits non-zero —
 * that disagreement is what proves a dimension still catches the drift it was
 * built to catch.
 *
 * decision_review adds ONE thing the routing loop does not have: a per-candidate
 * `expectedFailedDimensions` pin. With nineteen dimensions, "this candidate
 * fails" is far too weak a statement to prove a specific dimension works — a
 * candidate seeded to trip `no_dashes` could fail for an unrelated reason and
 * the fixture would still agree. Naming the dimension turns each seeded defect
 * into a RED-first proof of THAT dimension.
 */

import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { scoreDecisionReview } from './scorer.js';
import { assembleDecisionReviewUserMessage, sectionsPresent } from './assemble.js';
import type { ScoreResult } from '../types.js';
import type { ExtractionMode } from '../task-adapter.js';
import type { DecisionReviewEvalFixture } from './types.js';

const HERE = dirname(fileURLToPath(import.meta.url));

/** The checked-in decision_review fixture directory. */
export const DECISION_REVIEW_FIXTURES_DIR = join(HERE, '..', '..', 'fixtures', 'decision-review');

/** The keys a file must carry to be a fixture rather than some other JSON. */
const REQUIRED_FIXTURE_KEYS = ['id', 'input', 'candidates', 'expected'] as const;

/**
 * Load every `*.json` fixture from `dir`, sorted by filename — VALIDATING each
 * one and REFUSING an empty load.
 *
 * ⚠ The unvalidated version of this function made the flagship artefact
 * unreproducible. It globbed every `*.json` in the directory and cast the
 * result, so once the baseline run wrote its report JSON alongside the capture
 * fixtures, the README's own documented command crashed on the report file. The
 * committed evidence could not be regenerated by following the committed
 * instructions.
 *
 * Two defences, both fail-loud:
 *   - a `*.json` that is not fixture-shaped is REFUSED BY NAME, listing the
 *     keys it lacks. Skipping it silently would let a typo'd fixture vanish
 *     from a pack that still reported "all fixtures agree";
 *   - a load that yields ZERO fixtures THROWS. An empty pack makes every
 *     downstream assertion pass by iterating nothing — trap 13, at the level
 *     above the scorer, where it would take the whole suite green with it.
 */
export function loadDecisionReviewFixtures(
  dir: string = DECISION_REVIEW_FIXTURES_DIR,
): DecisionReviewEvalFixture[] {
  const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  const fixtures: DecisionReviewEvalFixture[] = [];
  for (const file of files) {
    const path = join(dir, file);
    let parsed: unknown;
    try {
      parsed = JSON.parse(readFileSync(path, 'utf-8'));
    } catch (err) {
      throw new Error(`${path} is not valid JSON: ${err instanceof Error ? err.message : String(err)}`);
    }
    const record = parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)
      ? (parsed as Record<string, unknown>)
      : null;
    const missing = record === null
      ? [...REQUIRED_FIXTURE_KEYS]
      : REQUIRED_FIXTURE_KEYS.filter((k) => !(k in record));
    if (missing.length > 0) {
      throw new Error(
        `${path} is not a decision_review fixture (missing: ${missing.join(', ')}). ` +
          'The fixture directory must contain ONLY fixtures — put run reports somewhere else, ' +
          'and never beside the fixtures they were produced from.',
      );
    }
    fixtures.push(record as unknown as DecisionReviewEvalFixture);
  }
  if (fixtures.length === 0) {
    throw new Error(
      `no decision_review fixtures found in ${dir}. Refusing an empty pack: every assertion ` +
        'downstream would pass by iterating nothing.',
    );
  }
  return fixtures;
}

/**
 * Extract the decision_review output object from raw model text.
 *
 * The wire contract is "return ONLY a JSON object, no markdown fences"
 * (`decision_review.txt` OUTPUT_SCHEMA), but real models fence anyway, so
 * fences are tolerated exactly as the runtime's own extractor tolerates them.
 * Anything that does not yield a JSON OBJECT is `raw_unparsed` — flagged, never
 * silently skipped, and scored as a failed turn by the extraction contract.
 */
export function extractDecisionReviewOutput(raw: string): {
  output: Record<string, unknown> | null;
  extraction: ExtractionMode;
} {
  let cleaned = raw.trim();
  if (cleaned.startsWith('```json')) cleaned = cleaned.slice(7);
  else if (cleaned.startsWith('```')) cleaned = cleaned.slice(3);
  if (cleaned.endsWith('```')) cleaned = cleaned.slice(0, -3);
  cleaned = cleaned.trim();

  try {
    const parsed: unknown = JSON.parse(cleaned);
    if (typeof parsed === 'object' && parsed !== null && !Array.isArray(parsed)) {
      return { output: parsed as Record<string, unknown>, extraction: 'json_text' };
    }
  } catch {
    // fall through
  }
  return { output: null, extraction: 'raw_unparsed' };
}

export interface DecisionReviewFixtureReport {
  readonly fixtureId: string;
  /**
   * Assembly fidelity: which PRODUCTION user-message sections this fixture
   * actually exercises, and how large the assembled message is. A fixture that
   * reaches none of the post-v11 sections is measuring the v11 surface no
   * matter what its description claims — so the pack shows it rather than
   * asserting it in prose.
   */
  readonly assembly: {
    readonly sections: readonly string[];
    readonly userMessageChars: number;
    readonly margin: number | null;
  };
  readonly scores: readonly ScoreResult[];
  readonly agreement: Readonly<Record<string, boolean>>;
  /**
   * Per-candidate RED-first agreement: did each candidate fail EXACTLY the
   * dimensions its fixture named — no fewer AND NO MORE? `true` when the
   * fixture named none.
   */
  readonly dimensionAgreement: Readonly<Record<string, boolean>>;
  /** Per-candidate measured/NA/passed split, for reporting an honest N/M. */
  readonly counts: Readonly<Record<string, { measured: number; notApplicable: number; passed: number }>>;
  readonly ok: boolean;
}

/** Assemble + score one fixture; report assembly fidelity and both agreements. */
export function runDecisionReviewFixture(
  fixture: DecisionReviewEvalFixture,
): DecisionReviewFixtureReport {
  const { userMessage, margin } = assembleDecisionReviewUserMessage(fixture.input);

  const scores: ScoreResult[] = fixture.candidates.map((c) =>
    scoreDecisionReview({ output: c.output, input: fixture.input, candidateLabel: c.label }),
  );

  // COMPLETENESS FIRST. An unlisted candidate used to default to "agrees",
  // so a candidate could be dropped from `expected` — by a rename, a merge, or
  // a hand edit — and the pack would keep reporting full agreement while
  // asserting nothing about it. A missing entry is now a hard error.
  const missingExpectations = fixture.candidates
    .filter((c) => !(c.label in fixture.expected))
    .map((c) => c.label);
  if (missingExpectations.length > 0) {
    throw new Error(
      `fixture ${fixture.id}: candidate(s) [${missingExpectations.join(', ')}] have no entry in ` +
        '`expected`. An unlisted candidate would be scored and then silently ignored.',
    );
  }

  const agreement: Record<string, boolean> = {};
  const dimensionAgreement: Record<string, boolean> = {};
  const counts: Record<string, { measured: number; notApplicable: number; passed: number }> = {};
  for (const s of scores) {
    agreement[s.candidate] = s.pass === fixture.expected[s.candidate];
    counts[s.candidate] = {
      measured: s.measured,
      notApplicable: s.notApplicable,
      passed: s.passed,
    };

    const expectedFailed = fixture.expectedFailedDimensions?.[s.candidate];
    if (expectedFailed === undefined || expectedFailed.length === 0) {
      dimensionAgreement[s.candidate] = true;
    } else {
      // EXACT set equality, not subset. The docstring said "EXACTLY" from the
      // start; the implementation used `every(name => failed.has(name))`, which
      // only checks the named dimensions are AMONG the failures. Three of the
      // twenty seeds were failing extra dimensions nobody had noticed, and the
      // README, PR body and evidence file all repeated the "fails exactly the
      // dimension each names" claim on the strength of a check that could not
      // have detected otherwise.
      const failed = [...new Set(s.dimensions.filter((d) => d.status === 'fail').map((d) => d.name))].sort();
      const named = [...new Set(expectedFailed)].sort();
      dimensionAgreement[s.candidate] =
        failed.length === named.length && failed.every((n, i) => n === named[i]);
    }
  }

  const ok =
    Object.values(agreement).every(Boolean) && Object.values(dimensionAgreement).every(Boolean);

  return {
    fixtureId: fixture.id,
    assembly: {
      sections: sectionsPresent(userMessage),
      userMessageChars: userMessage.length,
      margin,
    },
    scores,
    agreement,
    dimensionAgreement,
    counts,
    ok,
  };
}
