describe('assertEditOptionContainment (#278 Gate 2 containment)', () => {
  const ctx = { factorLabel: 'Annual Cost', step1OptionLabels: ['Engage an offshore partner', 'Hire locally'] };

  it('PASS — safe defer (graph unchanged)', () => {
    const r = assertEditOptionContainment(res({ assistant_text: "I wasn't able to make that change safely." }), ctx);
    expect(r.ok).toBe(true);
    if (r.ok) expect(r.evidence).toMatch(/path=defer/);
  });

  it('PASS — clarification back', () => {
    const r = assertEditOptionContainment(res({ assistant_text: 'Which option do you mean?' }), ctx);
    expect(r.ok).toBe(true);
    if (r.ok) expect(r.evidence).toMatch(/path=clarify/);
  });

  it('PASS — clean apply that references the option (strict path working)', () => {
    const r = assertEditOptionContainment(
      res({ assistant_text: 'Updated the Engage an offshore partner option as requested.' }),
      ctx,
    );
    expect(r.ok).toBe(true);
    if (r.ok) expect(r.evidence).toMatch(/path=applied_option_ref/);
  });

  it('FAIL — value-parse leak ("You gave unknown")', () => {
    const r = assertEditOptionContainment(res({ assistant_text: 'You gave unknown for the value.' }), ctx);
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('edit_option_value_parse_leak');
  });

  it('FAIL — misapplied as a factor-value update', () => {
    const r = assertEditOptionContainment(
      res({ assistant_text: 'Updated Annual Cost to 0.9.' }),
      ctx,
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('edit_option_misapplied_as_factor');
  });

  it('FAIL — unverifiable apply claim (references neither option nor factor)', () => {
    const r = assertEditOptionContainment(res({ assistant_text: 'Updated the value as requested.' }), ctx);
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('edit_option_unverifiable_apply_claim');
  });

  // Review comment 1 — option labels unavailable.
  it('FAIL (precondition) — missing option labels + mutation acknowledgement', () => {
    // No step1OptionLabels in ctx: an acknowledged edit cannot be verified for
    // containment → explicit precondition failure, NOT a silent pass and NOT a
    // misleading unverifiable_apply_claim.
    const r = assertEditOptionContainment(
      res({ assistant_text: 'Updated the option as requested.' }),
      { factorLabel: 'Annual Cost' },
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('edit_option_missing_option_labels');
  });

  it('PASS — missing option labels + safe defer (graph unchanged, no leak)', () => {
    // With no mutation acknowledgement, a safe defer is valid containment even
    // when option labels are unavailable — labels are only required to verify
    // an apply-claim.
    const r = assertEditOptionContainment(
      res({ assistant_text: "I wasn't able to make that change safely." }),
      undefined,
    );
    expect(r.ok).toBe(true);
    if (r.ok) expect(r.evidence).toMatch(/path=defer/);
  });
});

