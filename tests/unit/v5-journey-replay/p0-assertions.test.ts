describe('assertDgaiResultState', () => {
  it('passes on a populated analysis_result block', () => {
    const r = assertDgaiResultState(res({ assistant_text: 'ok', blocks: [ANALYSIS_RESULT_BLOCK] }));
    expect(r.ok).toBe(true);
  });

  it('fails when the analysis_result block is absent', () => {
    const r = assertDgaiResultState(res({ assistant_text: 'ok', blocks: [] }));
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('dgai_result_state_absent');
  });

  it('fails when leading_option_id missing', () => {
    const r = assertDgaiResultState(
      res({ assistant_text: 'ok', blocks: [{ type: 'analysis_result', win_probabilities: { a: 0.6, b: 0.4 } }] }),
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('dgai_leading_option_missing');
  });

  it('fails when fewer than 2 win probabilities', () => {
    const r = assertDgaiResultState(
      res({ assistant_text: 'ok', blocks: [{ type: 'analysis_result', leading_option_id: 'o1', win_probabilities: { o1: 1 } }] }),
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('dgai_win_probabilities_too_few');
  });

  it('fails on a catastrophic leak in the summary (raw id)', () => {
    const r = assertDgaiResultState(
      res({
        assistant_text: 'ok',
        blocks: [{ ...ANALYSIS_RESULT_BLOCK, summary: 'Leading option is opt_hire by margin.' }],
      }),
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('dgai_summary_catastrophic_leak');
  });
});

