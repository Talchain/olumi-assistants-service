// assertWhatWouldFlipChip (#277 fresh chip-click)
// ---------------------------------------------------------------------------
describe('assertWhatWouldFlipChip (#277 fresh)', () => {
  const goodBody = {
    assistant_text:
      'Within the tested range, no single factor on its own reached a tipping point that would change which option leads.',
    blocks: [ANALYSIS_RESULT_BLOCK],
    suggested_actions: [{ id: 'c1', label: 'Explore drivers', message: 'see drivers' }],
  };

  it('PASS — non-empty, honest, dispatch not capturable (no _timings)', () => {
    const r = assertWhatWouldFlipChip(res(goodBody));
    expect(r.ok).toBe(true);
    if (r.ok) expect(r.evidence).toMatch(/dispatch=not_capturable/);
  });

  it('PASS — deterministic dispatch proven via _timings (llm_calls=0)', () => {
    const r = assertWhatWouldFlipChip(
      res({ ...goodBody, _timings: { turn: { handler_id: 'what_would_flip', llm_calls_used: 0 } } }),
    );
    expect(r.ok).toBe(true);
    if (r.ok) expect(r.evidence).toMatch(/dispatch=deterministic/);
  });

  it('FAIL — empty blocks AND actions', () => {
    const r = assertWhatWouldFlipChip(res({ assistant_text: 'text only', blocks: [], suggested_actions: [] }));
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('wwf_chip_empty_blocks_actions');
  });

  it('FAIL — routed through the LLM (llm_calls > 0)', () => {
    const r = assertWhatWouldFlipChip(
      res({ ...goodBody, _timings: { turn: { handler_id: 'what_would_flip', llm_calls_used: 1 } } }),
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('wwf_chip_routed_through_llm');
  });

  it('FAIL — wrong handler id', () => {
    const r = assertWhatWouldFlipChip(
      res({ ...goodBody, _timings: { turn: { handler_id: 'explain_results', llm_calls_used: 0 } } }),
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('wwf_chip_unexpected_handler');
  });

  it('FAIL — dishonest contradiction (no tipping point AND could flip)', () => {
    const r = assertWhatWouldFlipChip(
      res({
        ...goodBody,
        assistant_text:
          'No single factor on its own reached a tipping point. The picture appears fragile, so even small adjustments could shift which option leads.',
      }),
    );
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.failing_contract).toBe('wwf_chip_contradiction_no_flip_but_could_flip');
  });
});

