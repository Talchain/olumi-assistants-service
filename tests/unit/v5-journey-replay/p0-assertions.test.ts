// findEnrichmentLeakCarriers + collectLeakFindings (public surfaces only)
// ---------------------------------------------------------------------------
describe('findEnrichmentLeakCarriers (#277 carriers)', () => {
  it('detects carrier keys and value markers at depth', () => {
    const enrichment = {
      results: { report: {} },
      _meta: { seed: 1 },
      factor_sensitivity: [{ interpretation: 'fine' }],
      // `isl_engine` is carried as a string VALUE (per #277, inside m1_coaching),
      // and `[REDACTED]` is a redaction sentinel that survived on a kept field.
      decision_review: { note: '[REDACTED]', engine: 'generated by isl_engine' },
    };
    const findings = findEnrichmentLeakCarriers(enrichment);
    const details = findings.map((f) => `${f.kind}:${f.detail}`);
    expect(details).toContain('carrier_key:_meta');
    expect(details).toContain('carrier_key:seed');
    expect(details).toContain('value_marker:isl_engine');
    expect(details).toContain('value_marker:[REDACTED]');
  });

  it('returns nothing for a clean kept-field enrichment', () => {
    const enrichment = {
      results: { report: { option_probabilities: { win_probability: 0.6 } } },
      option_comparison: {},
      factor_sensitivity: [{ interpretation: 'Engineering Capacity is the top driver.' }],
      robustness: { band: 'stable' },
    };
    expect(findEnrichmentLeakCarriers(enrichment)).toHaveLength(0);
  });
});

describe('collectLeakFindings', () => {
  it('scans assistant_text, chips, and analysis_result.summary (prose) always', () => {
    const findings = collectLeakFindings(
      {
        assistant_text: 'The set_factor_value handler ran.',
        suggested_actions: [{ id: 'c1', label: 'opt_hire', message: 'ok' }],
        blocks: [{ type: 'analysis_result', summary: 'graph_hash leaked' }],
      } as never,
      { scanEnrichment: false },
    );
    const surfaces = findings.map((f) => f.surface);
    expect(surfaces).toContain('assistant_text');
    expect(surfaces).toContain('chip');
    expect(surfaces).toContain('analysis_result_summary');
    // Enrichment NOT scanned when scanEnrichment is false.
    expect(surfaces).not.toContain('enrichment');
  });

  it('scans public enrichment only when scanEnrichment is true', () => {
    const body = {
      assistant_text: 'clean',
      blocks: [{ type: 'analysis_result', summary: 'clean', enrichment: { _meta: { x: 1 } } }],
    } as never;
    expect(collectLeakFindings(body, { scanEnrichment: false }).some((f) => f.surface === 'enrichment')).toBe(false);
    expect(collectLeakFindings(body, { scanEnrichment: true }).some((f) => f.surface === 'enrichment')).toBe(true);
  });
});

