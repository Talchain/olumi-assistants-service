/**
 * ⭐⭐ ROADMAP 2.1266 — the option-effect WRITE PATH resolver.
 *
 * ═══ WHY THIS FILE EXISTS ═══
 * On deployed `293da07` the product's repair copy advises, verbatim:
 *
 *   "Tell me what it changes, like this: Set the <option> option's effect on
 *    <factor> to 0.6"
 *
 * …and sending exactly that returns "…still has no effect value…" with nothing
 * written. No wire verb on the build could set an option's effect value: the
 * `system_event` types carry none, and the chat path depended on the edit LLM
 * emitting the sanctioned intervention `update_node` — which, on the witnessed
 * J4 t5 turn, it did not. P8 at its purest: the product asked a question it
 * could not accept the answer to.
 *
 * ⚠ THE CORPUS IS THE WIRE'S, NOT MINE (trap 22 / trap 16). Both the graph and
 * the two message shapes are the VERBATIM captures in
 * `__tests__/fixtures/witness-2026-08-17/j4-wrong-entity-write.json`
 * (deployed CEE `8be62df`, scenario 289c2690…). `wire.t4_chip_message` is the
 * product's OWN advised phrasing, generated by
 * `buildConfigureOptionAdvisedFormat` on a real turn — a self-authored fixture
 * would have encoded my model of the advised format rather than the product's.
 * Historic record: append, never edit (trap 14b).
 *
 * ⚠ EXTRACTOR-DELETION OBLIGATION (trap 19). Deleting the option-label
 * resolution in `matchLabels`, or the `EFFECT_FRAMED_TRIGGERS` gate, or the
 * `readOptionEffectValue` scale guard MUST turn assertions here RED. The
 * DISCRIMINATING PAIR at the bottom is the binding proof: renaming the option
 * the message names withdraws the write (RED-equivalent), while renaming a
 * DIFFERENT option leaves the verdict byte-identical (GREEN) — neither alone
 * shows identity binding, the pair does.
 */

