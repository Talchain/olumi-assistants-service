function res(body: unknown, status = 200, elapsed = 100): FetchResult {
  return { status, body: body as never, elapsed_ms: elapsed };
}

const ANALYSIS_RESULT_BLOCK = {
  type: 'analysis_result',
  summary: 'Hire Two Senior Engineers Locally leads at about 63%.',
  leading_option_id: 'opt_hire',
  win_probabilities: { opt_hire: 0.63, opt_offshore: 0.37 },
};

// ---------------------------------------------------------------------------
// extractDgaiState
// ---------------------------------------------------------------------------
describe('extractDgaiState', () => {
  it('returns present:false when no analysis_result block', () => {
    expect(extractDgaiState({ blocks: [{ type: 'coaching' }] } as never)).toEqual({ present: false });
  });

  it('extracts leading option + win count (object-keyed) + summary/enrichment flags', () => {
    const d = extractDgaiState({
      blocks: [{ ...ANALYSIS_RESULT_BLOCK, enrichment: { results: {} } }],
    } as never);
    expect(d.present).toBe(true);
    expect(d.leading_option_id).toBe('opt_hire');
    expect(d.win_probability_count).toBe(2);
    expect(d.has_summary).toBe(true);
    expect(d.has_enrichment).toBe(true);
  });

  it('counts array-shaped win_probabilities', () => {
    const d = extractDgaiState({
      blocks: [{ type: 'analysis_result', leading_option_id: 'o1', win_probabilities: [0.6, 0.4] }],
    } as never);
    expect(d.win_probability_count).toBe(2);
  });
});

